export function getBotReply(messageText) {
  const text = messageText.toLowerCase();

  if (text === '/start' || text === 'привет') {
    return 'Привет! Я бот, который поможет тебе в варке пива или приготовлении самогона. Рассчитать сколько воды добавить для разбавления самогона и сколько градусов имеет твой самогон, если рефрактометр показывает определенное количество сахара. Также планирую помощь в приготовлении пива.';
  }
  
  if (text === 'кто ты') {
    return 'Я работаю на Cloudflare Workers и написан на JavaScript.';
  }

  // По умолчанию — эхо
  return `Ты написал: ${messageText}`;
}